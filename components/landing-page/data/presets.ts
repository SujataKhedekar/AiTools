export function buildDesignConfigFromBrief(brief: BusinessBrief): DesignConfig {
  const preset = DESIGN_STYLE_METADATA[brief.designStyle] || DESIGN_STYLE_METADATA['modern-minimal'];
  return {
    styleId: brief.designStyle,
    primaryColor: brief.brandColors.primary || preset.fallbackPalette.primary,
    secondaryColor: brief.brandColors.secondary || preset.fallbackPalette.secondary,
    backgroundColor: brief.brandColors.background || preset.defaults.backgroundColor,
    surfaceColor: preset.defaults.surfaceColor,
    textColor: preset.defaults.textColor,
    headingFont: preset.defaults.headingFont,
    bodyFont: preset.defaults.bodyFont,
    buttonStyle: preset.defaults.buttonStyle,
    borderRadius: preset.defaults.borderRadius,
    spacingScale: preset.defaults.spacingScale,
    animationsEnabled: preset.defaults.animationsEnabled,
    stickyMobileCta: preset.defaults.stickyMobileCta,
  };
}
