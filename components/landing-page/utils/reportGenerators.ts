import type { GeneratedCodeFile, GeneratedLandingPage } from '../types/aivora';
import { calculateQualityScore } from './qualityScore';

export function generateDocumentationFiles(page: GeneratedLandingPage): GeneratedCodeFile[] {
  const quality = calculateQualityScore(page);
  const enabledSections = page.sections.filter((s) => s.enabled);

  const readme = `# ${page.brief.businessName} — ${page.brief.productName} Landing Page

Generated by **AIVORA** on ${new Date(page.generatedAt).toISOString().split('T')[0]}.

## Project Structure

- \`html/\` — Standalone semantic HTML5, modular CSS, accessible vanilla JS, and JSON-LD schema
- \`react-tailwind/\` — Modular React + TypeScript + Tailwind CSS components
- \`nextjs-ts/\` — Next.js App Router (TypeScript + Tailwind CSS + Metadata API + JSON-LD)
- \`bootstrap/\` — Bootstrap 5 responsive landing page template
- \`reports/\` — SEO metadata report, Copywriting document, CTA recommendations, CRO audit report, and JSON-LD schema

## Setup Instructions

### Option A: Static HTML / CSS / JS
Open \`html/index.html\` via any static web server (e.g., \`npx serve html\`).

### Option B: React + Tailwind
\`\`\`bash
cd react-tailwind
npm install
npm run dev
\`\`\`

### Option C: Next.js App Router (TypeScript)
\`\`\`bash
cd nextjs-ts
npm install
npm run dev
\`\`\`

## Form & CTA Integration Setup

${
  page.brief.integrations.formKind === 'none'
    ? 'No lead/contact form was enabled on this page.'
    : page.brief.integrations.formEndpointUrl
      ? `Form submissions are configured to POST JSON payloads to \`${page.brief.integrations.formEndpointUrl}\`.`
      : `**Action Required:** No external form endpoint URL was configured during export. The exported form includes client-side validation and displays a configuration notice until you set your form handler URL (e.g., Formspree, HubSpot, or a custom \`/api/lead\` route).`
}

## Environment Variables (.env.example)

If deploying the full AIVORA generator or adding a server-side lead handler, configure:
- \`GEMINI_API_KEY\` (server-side only, never expose in client bundles)
- \`LEAD_WEBHOOK_URL\` (optional CRM/email forwarding endpoint)

## Next.js Integration Instructions

1. Copy \`nextjs-ts/components/*\` into your Next.js \`src/components/\` or \`components/\` folder.
2. Merge the \`metadata\` export from \`nextjs-ts/app/layout.tsx\` into your target route's \`page.tsx\` or \`layout.tsx\`.
3. Render the validated \`<script type="application/ld+json">\` blocks from \`reports/schema.json\` inside the page component.
4. Connect the \`ConversionForm\` \`onSubmit\` handler to a Next.js Route Handler (\`app/api/leads/route.ts\`).

## Known Limitations

- Bundled preview images are included under \`public/landing-page/assets/\` in the exported Next.js and React projects.
- AIVORA Quality Scores (${quality.overallScore}/100) are structural/SEO readiness assessments, not official Google Search or PageSpeed guarantees.
- Live conversion performance must be measured via controlled analytics and A/B experiments on real traffic.
`;

  const seoReport = `# SEO Metadata & Structured Data Report

**Business:** ${page.brief.businessName}
**Primary Keyword:** ${page.seo.keywordStrategy.primaryKeyword}
**Search Intent:** ${page.seo.keywordStrategy.searchIntent}

## Metadata
- **SEO Title (${page.seo.metadata.seoTitle.length} chars):** ${page.seo.metadata.seoTitle}
- **Meta Description (${page.seo.metadata.metaDescription.length} chars):** ${page.seo.metadata.metaDescription}
- **Canonical URL:** ${page.seo.metadata.canonicalUrl}
- **Open Graph Title:** ${page.seo.metadata.ogTitle}
- **Open Graph Description:** ${page.seo.metadata.ogDescription}
- **OG Image Recommendation:** ${page.seo.metadata.ogImageRecommendation}

## Keyword Strategy
- **Secondary Keywords:** ${page.seo.keywordStrategy.secondaryKeywords.join(', ') || 'None'}
- **Semantic Keywords:** ${page.seo.keywordStrategy.semanticKeywords.join(', ')}
- **Related Search Terms:** ${page.seo.keywordStrategy.relatedSearchTerms.join(', ')}

### Placement Recommendations
${page.seo.keywordStrategy.placementRecommendations.map((r) => `- ${r}`).join('\n')}

## Heading Structure
- **H1 (${page.seo.headingStructure.h1Count}):** ${page.seo.headingStructure.h1Text}
- **H2s:**
${page.seo.headingStructure.h2List.map((h) => `  - ${h}`).join('\n')}
- **H3s:**
${page.seo.headingStructure.h3List.map((h) => `  - ${h}`).join('\n')}

## JSON-LD Eligibility & Validation
${page.seo.jsonLdSchemas
  .map(
    (s) =>
      `- **${s.schemaType}**: ${s.eligible ? (s.isValidJson ? 'Eligible & Valid JSON-LD' : `Invalid (${s.validationErrors.join(', ')})`) : 'Omitted'} — ${s.eligibilityReason}`
  )
  .join('\n')}
`;

  const copyDoc = `# Copywriting Document — ${page.brief.businessName}

**Copywriting Framework:** ${page.strategy.recommendedFramework}
**Framework Rationale:** ${page.strategy.frameworkRationale}
**Recommended Tone:** ${page.strategy.recommendedTone}

${enabledSections
  .map(
    (sec, i) => `## ${i + 1}. ${sec.navLabel} (${sec.type})
- **Headline:** ${sec.headline}
${sec.subheadline ? `- **Subheadline:** ${sec.subheadline}\n` : ''}- **Body Copy:** ${sec.description}
${sec.primaryCtaText ? `- **Primary CTA:** ${sec.primaryCtaText} -> ${sec.primaryCtaDestination || ''}\n` : ''}${
      sec.items?.length
        ? `\n### Items\n${sec.items.map((it) => `- **${it.title}**: ${it.description}${it.benefit ? ` *(Benefit: ${it.benefit})*` : ''}`).join('\n')}\n`
        : ''
    }${
      sec.faqs?.length
        ? `\n### FAQs\n${sec.faqs.map((f) => `- **Q: ${f.question}**\n  A: ${f.answer}`).join('\n')}\n`
        : ''
    }`
  )
  .join('\n')}
`;

  const ctaDoc = `# CTA Recommendations — ${page.brief.businessName}

**Objective Alignment:** ${page.ctaSuite.objectiveAlignment}
**Compliance Note:** ${page.ctaSuite.complianceNote}

${page.ctaSuite.slots
  .map(
    (slot) => `## ${slot.slot}
- **Recommended Text:** ${slot.recommended.text}
- **Placement:** ${slot.recommended.placement}
- **Intended Action:** ${slot.recommended.intendedAction}
- **Supporting Message:** ${slot.recommended.supportingMessage}
- **Destination:** ${slot.recommended.destination}

### Alternatives
${slot.variations.map((v) => `- **${v.text}** (${v.placement}) — ${v.supportingMessage}`).join('\n')}
`
  )
  .join('\n')}
`;

  const croDoc = `# Conversion Rate Optimization (CRO) Audit Report

**Aivora Quality Score:** ${quality.overallScore}/100 (${quality.gradeLabel})
*${quality.disclaimer}*

## Component Breakdown
${quality.components.map((c) => `- **${c.label}: ${c.score}/${c.maxScore}** — ${c.formulaExplanation}`).join('\n')}

## Executive Summary
${page.cro.executiveSummary}

## Identified Weaknesses & Recommendations
${page.cro.weaknesses
  .map(
    (w) => `### [${w.severity}] ${w.area}
- **Finding:** ${w.finding}
- **Recommendation:** ${w.recommendation}`
  )
  .join('\n\n')}

## A/B Testing Hypotheses
${page.cro.abTestingSuggestions
  .map(
    (ab) => `### ${ab.element}
- **Hypothesis:** ${ab.hypothesis}
- **Control (A):** ${ab.variantA}
- **Challenger (B):** ${ab.variantB}
- **Metric to Observe:** ${ab.primaryMetricToObserve}`
  )
  .join('\n\n')}

---
*${page.cro.disclaimer}*
`;

  const combinedSchemas = page.seo.jsonLdSchemas
    .filter((s) => s.eligible && s.isValidJson)
    .map((s) => JSON.parse(s.jsonString));

  const envExample = `# Server-side Gemini API Key (never expose in browser bundles)
GEMINI_API_KEY="YOUR_GEMINI_API_KEY"

# Optional webhook endpoint for lead/contact form submissions
LEAD_WEBHOOK_URL="https://hooks.example.com/your-endpoint"
`;

  return [
    { path: 'README.md', language: 'markdown', content: readme },
    { path: '.env.example', language: 'markdown', content: envExample },
    { path: 'reports/seo-metadata-report.md', language: 'markdown', content: seoReport },
    { path: 'reports/copywriting-document.md', language: 'markdown', content: copyDoc },
    { path: 'reports/cta-recommendations.md', language: 'markdown', content: ctaDoc },
    { path: 'reports/cro-audit-report.md', language: 'markdown', content: croDoc },
    {
      path: 'reports/schema.json',
      language: 'json',
      content: JSON.stringify(combinedSchemas, null, 2),
    },
  ];
}
