import React, { useState } from 'react';
import {
  ArrowRight,
  Check,
  ChevronDown,
  ChevronLeft,
  ChevronRight,
  Layers,
  Play,
  SlidersHorizontal,
  Wand2,
} from 'lucide-react';
import { PRESENTATION_TEMPLATES, TEMPLATE_CATEGORIES } from '../lib/templates';
import type { PresentationTemplate, UserProfile } from '../types/deck';
import { SlideCanvasRenderer } from './SlideCanvasRenderer';

interface LandingPageProps {
  user: UserProfile | null;
  onStartGenerate: (initialPrompt: string) => void;
  onUseTemplate: (template: PresentationTemplate) => void;
  onOpenAuth: (mode: 'login' | 'signup') => void;
  onOpenDashboard: () => void;
  onSelectPlan: (plan: 'free' | 'pro' | 'business') => void;
}

